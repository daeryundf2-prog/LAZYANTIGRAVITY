#!/usr/bin/env node
import * as fs from "fs"
import * as path from "path"

const TARGET_FILES = [
  "CLAUDE.md",
  "GEMINI.md",
  ".agents.md",
  ".cursorrules",
  ".clinerules",
  ".windsurfrules"
]

const POSSIBLE_MASTER_PATHS = [
  path.join(process.cwd(), ".agents", "AGENTS.md"),
  path.join(process.cwd(), "AGENTS.md"),
]

function getPlatformForFile(filename) {
  if (filename === "CLAUDE.md") return "CLAUDE"
  if (filename === "GEMINI.md") return "GEMINI"
  if (filename === ".agents.md") return "AGENTS"
  if (filename === ".cursorrules") return "CURSOR"
  if (filename === ".clinerules") return "CLINE"
  if (filename === ".windsurfrules") return "WINDSURF"
  return "GENERIC"
}

function preprocessRules(content, platform) {
  // Pattern to find: <!-- IF PLATFORMS -->...<!-- ENDIF -->
  const regex = /<!--\s*IF\s+([A-Z0-9_,\s]+)-->([\s\S]*?)<!--\s*ENDIF\s*-->/gi

  return content.replace(regex, (match, platformsStr, innerContent) => {
    const platforms = platformsStr.split(/[\s,]+/).map(p => p.trim().toUpperCase()).filter(Boolean)
    if (platforms.includes(platform.toUpperCase()) || platforms.includes("ALL")) {
      return innerContent // Keep the inner content (strip markers)
    }
    return "" // Remove the entire block
  })
}

function syncFiles(masterPath) {
  let masterContent = ""
  try {
    masterContent = fs.readFileSync(masterPath, "utf-8")
    console.log(`[Rules Sync] 마스터 규칙 파일을 로드했습니다: ${masterPath} (${masterContent.length} bytes)`)
  } catch (e) {
    console.error(`[Rules Sync] 에러: 마스터 규칙 파일을 읽을 수 없습니다.`, e)
    return false
  }

  let successCount = 0
  for (const filename of TARGET_FILES) {
    const outputPath = path.join(process.cwd(), filename)
    try {
      const platform = getPlatformForFile(filename)
      const compiledContent = preprocessRules(masterContent, platform)

      // 헤더 주입 (마스터 파일 변경 권고 메시지)
      const header = `<!-- OMO AGENT RULES: DO NOT EDIT THIS FILE DIRECTLY. EDIT ${path.relative(process.cwd(), masterPath)} INSTEAD. -->\n\n`
      fs.writeFileSync(outputPath, header + compiledContent, "utf-8")
      console.log(`[Rules Sync] 작성 완료: ${filename} (Platform: ${platform})`)
      successCount++
    } catch (err) {
      console.warn(`[Rules Sync] 경고: ${filename} 파일 생성 실패:`, err.message)
    }
  }

  console.log(`[Rules Sync] 동기화 프로세스 완료. 총 ${successCount}개 파일 업데이트 성공.`)
  return true
}

function run() {
  console.log("[Rules Sync] 동기화를 시작합니다...")

  let masterPath = ""

  // 1. 마스터 규칙 파일 탐색
  for (const p of POSSIBLE_MASTER_PATHS) {
    if (fs.existsSync(p)) {
      masterPath = p
      break
    }
  }

  if (!masterPath) {
    console.error("[Rules Sync] 에러: 마스터 규칙 파일 (AGENTS.md 또는 .agents/AGENTS.md)을 찾을 수 없습니다.")
    process.exit(1)
  }

  // 2. 동기화 수행
  const success = syncFiles(masterPath)
  if (!success) {
    process.exit(1)
  }

  // 3. 모니터링 모드 확인
  if (process.argv.includes("--watch") || process.argv.includes("-w")) {
    console.log(`[Rules Sync] 실시간 감시(Watch) 모드 가동 중: ${masterPath} 파일의 변경 사항을 감시합니다. Ctrl+C로 종료합니다.`)
    fs.watch(masterPath, (eventType, filename) => {
      if (eventType === "change") {
        console.log(`[Rules Sync] 파일 변경 감지됨: ${filename}. 다시 동기화 중...`)
        syncFiles(masterPath)
      }
    })
  }
}

run()
